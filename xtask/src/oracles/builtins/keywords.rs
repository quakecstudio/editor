//! off. Each program binds `f` first and then uses a word one way or the other, so `f` is bound
//! only when FTEQCC read the word as the program needs. Programs whose outcome a warning decides
//! are compiled with FTEQCC's `-Werror` and read with every warning of the profile an error.

