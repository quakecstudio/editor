//! The keyword family of the builtin differential (P2-119): programs whose words FTEQCC's
//! parser reads as keywords or as names by the `keyword_*` flags in force at them
//! (`docs/spec/dialect-fteqcc.md` FTEF-20), which `#pragma keyword`, `#pragma flag`, the `-K`,
