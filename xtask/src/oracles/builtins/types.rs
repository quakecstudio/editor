/// The programs of one option set, with what defines their neighbours first, each with whether
/// it is also compiled with `qcfuncs` off: the declarations are, where the flag changes what a
/// `*` and a `(` after the type are (FTEF-21.7); the types in every position are not.
fn programs() -> Vec<(String, bool)> {
    let mut programs: Vec<(String, bool)> = Vec::new();
    for prelude in PRELUDES {
        for member in MEMBERS {
            for head in HEADS {
                programs.push((format!("{prelude}{head} {{ {member} }};\n"), true));
            }
        }
        for head in HEADS {
            for tail in TAILS {
                programs.push((format!("{prelude}{head} {{ float a; }}{tail}\n"), true));
                programs.push((format!("{prelude}{head}{tail}\n"), true));
                programs.push((
                    format!("{prelude}void() g = {{ {head} {{ float a; }}{tail} }};\n"),
                    true,
                ));
                programs.push((
                    format!("{prelude}void() g = {{ local {head} {{ float a; }}{tail} }};\n"),
                    true,
                ));
                programs.push((format!("{prelude}void() g = {{ {head}{tail} }};\n"), true));
            }
        }
        for member in CLASS_MEMBERS {
            for head in CLASS_HEADS {
                programs.push((format!("{prelude}{head} {{ {member} }};\n"), true));
            }
        }
        for head in CLASS_HEADS {
            for tail in CLASS_TAILS {
                programs.push((format!("{prelude}{head} {{ float a; }}{tail}\n"), true));
                programs.push((format!("{prelude}{head}{tail}\n"), true));
                programs.push((
                    format!("{prelude}void() g = {{ {head} {{ float a; }}{tail} }};\n"),
                    true,
                ));
                programs.push((format!("{prelude}void() g = {{ {head}{tail} }};\n"), true));
            }
        }
        for source in PROGRAMS {
            programs.push((format!("{prelude}{source}\n"), true));
        }
        for ty in types() {
            for position in TYPE_POSITIONS {
                programs.push((format!("{prelude}{}", position.replace("{}", &ty)), false));
            }
        }
    }
    programs
}

/// The cases: each program with no option, with `-Fcaseinsens` and, where [`programs`] says,
/// with `qcfuncs` off.
pub(super) fn cases() -> Vec<Case> {
    let mut cases = Vec::new();
    for (source, qcfuncs_off) in programs() {
        let program = format!("{BIND}{source}");
        cases.push(Case::new(Dialect::Fteqcc, program.clone()));
        if qcfuncs_off {
            cases.push(Case::new(
                Dialect::Fteqcc,
                format!("#pragma flag disable qcfuncs\n{program}"),
            ));
        }
        cases.push(Case {
            options: vec!["-Fcaseinsens".to_owned()],
            ..Case::new(Dialect::Fteqcc, program)
        });
    }
    cases
}
