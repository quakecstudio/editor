//! Checks the crate layering in `layers.toml` (ARCH-1, `docs/layers.md`).
//!
//! Every workspace member must be in `layers.toml`, every entry there must be a
//! member, and a crate may depend only on crates in its own layer or a lower
//! one. Layers rank `L0` to `L7`, then `apps`. `tests` and `tooling` crates
//! sit outside the ranking: they may depend on any crate, and no crate may
//! depend on them. Normal, dev and build dependencies all count, including
//! target-specific ones.
//!
//! The table of crates in `docs/layers.md` is written from `layers.toml` and each
//! crate's package description (`cargo xtask layers --write`), and the check fails
//! when the table is not what they render, so the document cannot fall behind.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::Path;

use toml::{Table, Value};

use crate::{Report, print_outcome};

pub(crate) const FILE: &str = "layers.toml";
/// The document whose crate table is written from [`FILE`].
const DOC: &str = "docs/layers.md";
/// The line before the crate table in [`DOC`].
const TABLE_START: &str =
    "<!-- crates:start (generated by cargo xtask layers --write; do not edit by hand) -->";
/// The line after the crate table in [`DOC`].
const TABLE_END: &str = "<!-- crates:end -->";
const RANKED: [&str; 9] = ["L0", "L1", "L2", "L3", "L4", "L5", "L6", "L7", "apps"];
const UNRANKED: [&str; 2] = ["tests", "tooling"];
const DEPENDENCY_TABLES: [&str; 3] = ["dependencies", "dev-dependencies", "build-dependencies"];

/// Where a layer sits.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Rank {
    /// Position in [`RANKED`]: a crate may depend on its own rank or lower.
    Ranked(usize),
    /// `tests` or `tooling`: may depend on anything; nothing may depend on it.
    Unranked,
}

fn rank(layer: &str) -> Option<Rank> {
    if let Some(position) = RANKED.iter().position(|ranked| *ranked == layer) {
        Some(Rank::Ranked(position))
    } else if UNRANKED.contains(&layer) {
        Some(Rank::Unranked)
    } else {
        None
    }
}

/// A workspace member and the workspace crates it depends on.
#[derive(Debug)]
struct Member {
    manifest: String,
    /// The package's `description`, which is its row in the crate table.
    description: Option<String>,
    dependencies: BTreeSet<String>,
}

/// `cargo xtask layers`' arguments.
#[derive(clap::Args, Debug, Default)]
pub(crate) struct Args {
    /// Write the crate table of docs/layers.md instead of checking it.
    #[arg(long)]
    write: bool,
}

/// Runs `cargo xtask layers` with the arguments `args`.
pub(crate) fn main(root: &Path, args: &Args) -> Result<bool, String> {
    if !args.write {
        return Ok(print_outcome("layers", check(root)));
    }
    let doc = fs::read_to_string(root.join(DOC)).map_err(|error| format!("{DOC}: {error}"))?;
    let written = with_table(&doc, &table(root)?)?;
    fs::write(root.join(DOC), written).map_err(|error| format!("{DOC}: {error}"))?;
    eprintln!("layers: wrote the crate table of {DOC}");
    Ok(true)
}

/// Checks the layering, and that the crate table of `docs/layers.md` is the one
/// `layers.toml` and the crates' descriptions render.
pub(crate) fn check(root: &Path) -> Result<Report, String> {
    let mut report = check_dependencies(root)?;
    // A document or a description that is missing is one more problem beside the layering's,
    // not a reason to drop them.
    let rendered = fs::read_to_string(root.join(DOC))
        .map_err(|error| format!("{DOC}: {error}"))
        .and_then(|doc| Ok(with_table(&doc, &table(root)?)? == doc));
    match rendered {
        Ok(true) => report
            .passed
            .push(format!("{DOC} lists the crates of {FILE}")),
        Ok(false) => report.problems.push(format!(
            "{DOC}'s crate table differs from {FILE}; run cargo xtask layers --write"
        )),
        Err(error) => report.problems.push(error),
    }
    Ok(report)
}

/// The crate table: a row for each member in `layers.toml`, by layer and then by name, with
/// its package description on one line, a `|` in it escaped so it stays in its cell.
fn table(root: &Path) -> Result<String, String> {
    let crates = crates_table(root)?;
    let members = members(root)?;
    let mut table = String::from("| Layer | Crate | What it is |\n| --- | --- | --- |\n");
    for layer in RANKED.iter().chain(&UNRANKED) {
        for (name, member) in &members {
            if crates.get(name).and_then(Value::as_str) != Some(*layer) {
                continue;
            }
            let description = member
                .description
                .as_deref()
                .ok_or_else(|| format!("{}: the package has no description", member.manifest))?;
            let cell = description
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" ")
                .replace('|', "\\|");
            table.push_str(&format!("| {layer} | `{name}` | {cell} |\n"));
        }
    }
    Ok(table)
}

/// `doc` with `table` between its [`TABLE_START`] and [`TABLE_END`] lines.
fn with_table(doc: &str, table: &str) -> Result<String, String> {
    let (before, rest) = doc
        .split_once(TABLE_START)
        .ok_or_else(|| format!("{DOC} has no line {TABLE_START:?}"))?;
    let (_, after) = rest
        .split_once(TABLE_END)
        .ok_or_else(|| format!("{DOC} has no line {TABLE_END:?}"))?;
    Ok(format!("{before}{TABLE_START}\n{table}{TABLE_END}{after}"))
}

/// Checks every crate's layer and that it depends only on its own layer or lower.
fn check_dependencies(root: &Path) -> Result<Report, String> {
    let crates = crates_table(root)?;
    let members = members(root)?;
    let mut report = Report::default();

    let mut assigned = BTreeMap::new();
    for (name, layer) in &crates {
        let Some(layer) = layer.as_str() else {
            report
                .problems
                .push(format!("{FILE}: {name} must map to a layer name"));
            continue;
        };
        let Some(rank) = rank(layer) else {
            report.problems.push(format!(
                "{FILE}: {name} is in unknown layer {layer:?} (layers: {}, {})",
                RANKED.join(", "),
                UNRANKED.join(", ")
            ));
            continue;
        };
        if !members.contains_key(name) {
            report.problems.push(format!(
                "{FILE}: {name} is not a workspace member; remove it"
            ));
        }
        assigned.insert(name.as_str(), (layer, rank));
    }

    for (name, member) in &members {
        let Some(&(layer, rank)) = assigned.get(name.as_str()) else {
            if crates.contains_key(name) {
                continue;
            }
            report.problems.push(format!(
                "{}: crate {name} is missing from {FILE}; add it to a layer",
                member.manifest
            ));
            continue;
        };
        let mut ok = true;
        for dependency in &member.dependencies {
            let Some(&(dep_layer, dep_rank)) = assigned.get(dependency.as_str()) else {
                continue;
            };
            let allowed = match (rank, dep_rank) {
                (_, Rank::Unranked) => false,
                (Rank::Unranked, Rank::Ranked(_)) => true,
                (Rank::Ranked(own), Rank::Ranked(other)) => other <= own,
            };
            if !allowed {
                ok = false;
                report.problems.push(format!(
                    "{name} ({layer}) depends on {dependency} ({dep_layer}): a crate may depend \
                     only on crates in its own layer or lower, and never on tests or tooling"
                ));
            }
        }
        if ok {
            report.passed.push(format!(
                "{name} ({layer}) depends on {} workspace crates, none above it",
                member.dependencies.len()
            ));
        }
    }
    Ok(report)
}

/// The workspace members by package name, with the member crates each depends on.
fn members(root: &Path) -> Result<BTreeMap<String, Member>, String> {
    let manifest = read_toml(root, "Cargo.toml")?;
    let workspace = manifest
        .get("workspace")
        .and_then(Value::as_table)
        .ok_or("Cargo.toml has no [workspace]")?;
    let excluded: BTreeSet<&str> = strings(workspace.get("exclude")).collect();
    let mut dirs = Vec::new();
    for pattern in strings(workspace.get("members")) {
        if let Some(parent) = pattern.strip_suffix("/*") {
            let path = root.join(parent);
            let entries =
                fs::read_dir(&path).map_err(|error| format!("{}: {error}", path.display()))?;
            for entry in entries {
                let entry = entry.map_err(|error| format!("{}: {error}", path.display()))?;
                if entry.path().join("Cargo.toml").is_file() {
                    dirs.push(format!("{parent}/{}", entry.file_name().to_string_lossy()));
                }
            }
        } else {
            dirs.push(pattern.to_owned());
        }
    }
    let renames = workspace
        .get("dependencies")
        .and_then(Value::as_table)
        .map(|deps| {
            deps.iter()
                .map(|(key, value)| (key.clone(), package_name(key, value)))
                .collect::<BTreeMap<_, _>>()
        })
        .unwrap_or_default();

    let mut manifests = BTreeMap::new();
    for dir in dirs.iter().filter(|dir| !excluded.contains(dir.as_str())) {
        let path = format!("{dir}/Cargo.toml");
        let manifest = read_toml(root, &path)?;
        let Some(name) = manifest
            .get("package")
            .and_then(|package| package.get("name"))
            .and_then(Value::as_str)
        else {
            return Err(format!("{path} has no package name"));
        };
        manifests.insert(name.to_owned(), (path, manifest));
    }
    let mut members = BTreeMap::new();
    for (name, (path, manifest)) in &manifests {
        let mut tables: Vec<&Table> = DEPENDENCY_TABLES
            .iter()
            .filter_map(|key| manifest.get(*key).and_then(Value::as_table))
            .collect();
        if let Some(targets) = manifest.get("target").and_then(Value::as_table) {
            for target in targets.values() {
                tables.extend(
                    DEPENDENCY_TABLES
                        .iter()
                        .filter_map(|key| target.get(*key).and_then(Value::as_table)),
                );
            }
        }
        let mut dependencies = BTreeSet::new();
        for table in tables {
            for (key, value) in table {
                let inherited = value.get("workspace").and_then(Value::as_bool) == Some(true);
                let package = match (inherited, renames.get(key)) {
                    (true, Some(package)) => package.clone(),
                    (true, None) | (false, _) => package_name(key, value),
                };
                if manifests.contains_key(&package) {
                    dependencies.insert(package);
                }
            }
        }
        let description = manifest
            .get("package")
            .and_then(|package| package.get("description"))
            .and_then(Value::as_str)
            .map(str::to_owned);
        members.insert(
            name.clone(),
            Member {
                manifest: path.clone(),
                description,
                dependencies,
            },
        );
    }
    Ok(members)
}

/// The package a dependency entry names: its `package` key, or the key itself.
fn package_name(key: &str, value: &Value) -> String {
    value
        .get("package")
        .and_then(Value::as_str)
        .unwrap_or(key)
        .to_owned()
}

fn strings(value: Option<&Value>) -> impl Iterator<Item = &str> {
    value
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
}

/// The `[crates]` table of `layers.toml`.
fn crates_table(root: &Path) -> Result<Table, String> {
    let layers = read_toml(root, FILE)?;
    layers
        .get("crates")
        .and_then(Value::as_table)
        .cloned()
        .ok_or_else(|| format!("{FILE} has no [crates] table"))
}

/// Every crate `layers.toml` names with its layer, in the file's order; a crate mapped to
/// anything but a layer name is an error.
pub(crate) fn assignments(root: &Path) -> Result<Vec<(String, String)>, String> {
    crates_table(root)?
        .iter()
        .map(|(name, layer)| {
            let layer = layer
                .as_str()
                .ok_or_else(|| format!("{FILE}: {name} is not a string"))?;
            Ok((name.clone(), layer.to_owned()))
        })
        .collect()
}

fn read_toml(root: &Path, path: &str) -> Result<Table, String> {
    fs::read_to_string(root.join(path))
        .map_err(|error| format!("{path}: {error}"))?
        .parse::<Table>()
        .map_err(|error| format!("{path}: {error}"))
}

#[cfg(test)]
mod tests {
    #![expect(
        clippy::unwrap_used,
        clippy::indexing_slicing,
        reason = "test code: a failed unwrap or index is a failed test"
    )]

    use std::path::PathBuf;

    use super::*;
    use crate::test_dirs::fresh;

    /// One crate in a fixture workspace: name, directory, layer (`None` =
    /// missing from layers.toml) and extra manifest text (dependencies).
    struct Spec {
        name: &'static str,
        layer: Option<&'static str>,
        manifest: &'static str,
    }

    fn krate(name: &'static str, layer: &'static str, manifest: &'static str) -> Spec {
        Spec {
            name,
            layer: Some(layer),
            manifest,
        }
    }

    fn workspace(name: &str, specs: &[Spec], extra_layers: &str) -> PathBuf {
        let root = fresh(&format!("layers/{name}"));
        fs::create_dir_all(root.join("crates")).unwrap();
        fs::create_dir_all(root.join("fuzz")).unwrap();
        fs::write(
            root.join("Cargo.toml"),
            format!(
                "[workspace]\nmembers = [\"crates/*\"{}]\nexclude = [\"fuzz\"]\n\
                 [workspace.dependencies]\nrenamed-c = {{ path = \"crates/c\", package = \"c\" }}\n",
                if specs.iter().any(|spec| spec.name == "xtask") {
                    ", \"xtask\""
                } else {
                    ""
                }
            ),
        )
        .unwrap();
        let mut layers = String::from("[crates]\n");
        for spec in specs {
            let dir = if spec.name == "xtask" {
                root.join("xtask")
            } else {
                root.join("crates").join(spec.name)
            };
            fs::create_dir_all(&dir).unwrap();
            fs::write(
                dir.join("Cargo.toml"),
                format!("[package]\nname = \"{}\"\n{}", spec.name, spec.manifest),
            )
            .unwrap();
            if let Some(layer) = spec.layer {
                layers.push_str(&format!("{} = \"{layer}\"\n", spec.name));
            }
        }
        layers.push_str(extra_layers);
        fs::write(root.join(FILE), layers).unwrap();
        root
    }

    fn problems(name: &str, specs: &[Spec]) -> Vec<String> {
        check_dependencies(&workspace(name, specs, ""))
            .unwrap()
            .problems
    }

    const ON_C: &str = "[dependencies]\nc = { path = \"../c\" }\n";

    #[test]
    fn downward_and_same_layer_dependencies_pass() {
        let specs = [
            krate("a", "L0", ""),
            krate(
                "b",
                "L1",
                "[dependencies]\na = { path = \"../a\" }\nserde = \"1\"\n",
            ),
            krate("c", "L1", "[dependencies]\nb = { path = \"../b\" }\n"),
            krate("app", "apps", ON_C),
            krate(
                "it",
                "tests",
                "[dev-dependencies]\napp = { path = \"../app\" }\n",
            ),
            krate("xtask", "tooling", ""),
        ];
        assert_eq!(problems("ok", &specs), Vec::<String>::new());
    }

    #[test]
    fn an_l1_crate_depending_on_an_l3_crate_fails_naming_both() {
        let specs = [krate("vm", "L1", ON_C), krate("c", "L3", "")];
        let found = problems("upward", &specs);
        assert_eq!(found.len(), 1);
        assert!(
            found[0].starts_with("vm (L1) depends on c (L3)"),
            "{found:?}"
        );
    }

    #[test]
    fn every_dependency_kind_counts() {
        for (name, manifest) in [
            ("dev", "[dev-dependencies]\nc = { path = \"../c\" }\n"),
            ("build", "[build-dependencies]\nc = { path = \"../c\" }\n"),
            (
                "target",
                "[target.'cfg(unix)'.dependencies]\nc = { path = \"../c\" }\n",
            ),
            (
                "renamed",
                "[dependencies]\nrenamed-c = { workspace = true }\n",
            ),
            (
                "package",
                "[dependencies]\nother = { path = \"../c\", package = \"c\" }\n",
            ),
        ] {
            let specs = [krate("vm", "L1", manifest), krate("c", "L3", "")];
            assert_eq!(problems(name, &specs).len(), 1, "{name}");
        }
    }

    #[test]
    fn nothing_may_depend_on_tests_or_tooling() {
        let specs = [krate("app", "apps", ON_C), krate("c", "tooling", "")];
        assert_eq!(problems("on-tooling", &specs).len(), 1);
    }

    #[test]
    fn a_crate_missing_from_layers_toml_fails() {
        let specs = [
            krate("a", "L0", ""),
            Spec {
                name: "b",
                layer: None,
                manifest: "",
            },
        ];
        let found = problems("missing", &specs);
        assert_eq!(found.len(), 1);
        assert!(
            found[0].contains("crate b is missing from layers.toml"),
            "{found:?}"
        );
    }

    #[test]
    fn unknown_layers_and_stale_entries_fail() {
        let root = workspace("stale", &[krate("a", "L9", "")], "gone = \"L0\"\nnum = 3\n");
        let found = check_dependencies(&root).unwrap().problems;
        assert_eq!(found.len(), 3, "{found:?}");
    }

    #[test]
    fn a_layers_file_without_crates_is_an_error() {
        let root = workspace("no-table", &[], "");
        fs::write(root.join(FILE), "[other]\n").unwrap();
        assert!(check_dependencies(&root).is_err());
        fs::remove_file(root.join(FILE)).unwrap();
        assert!(check_dependencies(&root).is_err());
    }

    #[test]
    fn excluded_directories_are_not_members() {
        let root = workspace("excluded", &[krate("a", "L0", "")], "");
        fs::write(
            root.join("Cargo.toml"),
            "[workspace]\nmembers = [\"crates/*\"]\nexclude = [\"crates/a\"]\n",
        )
        .unwrap();
        let found = check_dependencies(&root).unwrap().problems;
        assert!(
            found[0].contains("a is not a workspace member"),
            "{found:?}"
        );
    }

    /// A workspace of one L0 crate `a` and one L1 crate `b`, each described, with `doc` as
    /// its `docs/layers.md`.
    fn documented(name: &str, doc: &str) -> PathBuf {
        let specs = [
            krate("b", "L1", "description = \"The second\"\n"),
            krate("a", "L0", "description = \"The first\"\n"),
        ];
        let root = workspace(name, &specs, "");
        fs::create_dir_all(root.join("docs")).unwrap();
        fs::write(root.join(DOC), doc).unwrap();
        root
    }

    const EMPTY_DOC: &str = "# Layers\n\n<!-- crates:start (generated by cargo xtask layers --write; do not edit by hand) -->\n<!-- crates:end -->\nAfter.\n";

    #[test]
    fn write_lists_each_crate_by_layer_and_the_check_then_passes() {
        let root = documented("table", EMPTY_DOC);
        let stale = check(&root).unwrap().problems;
        assert_eq!(stale.len(), 1, "{stale:?}");
        assert!(
            stale[0].contains("run cargo xtask layers --write"),
            "{stale:?}"
        );
        assert!(main(&root, &Args { write: true }).unwrap());
        let doc = fs::read_to_string(root.join(DOC)).unwrap();
        assert!(
            doc.contains(
                "| L0 | `a` | The first |\n| L1 | `b` | The second |\n<!-- crates:end -->\nAfter.\n"
            ),
            "{doc}"
        );
        assert!(doc.starts_with("# Layers\n\n<!-- crates:start"), "{doc}");
        assert_eq!(check(&root).unwrap().problems, Vec::<String>::new());
    }

    #[test]
    fn a_table_edited_by_hand_fails() {
        let root = documented("edited", EMPTY_DOC);
        assert!(main(&root, &Args { write: true }).unwrap());
        let doc = fs::read_to_string(root.join(DOC)).unwrap();
        fs::write(root.join(DOC), doc.replace("The first", "Something else")).unwrap();
        assert_eq!(check(&root).unwrap().problems.len(), 1);
    }

    #[test]
    fn a_document_without_the_table_lines_or_a_crate_without_a_description_is_an_error() {
        for (name, doc) in [
            ("no-start", "# Layers\n<!-- crates:end -->\n"),
            (
                "no-end",
                "<!-- crates:start (generated by cargo xtask layers --write; do not edit by hand) -->\n",
            ),
        ] {
            let root = documented(name, doc);
            assert_eq!(check(&root).unwrap().problems.len(), 1, "{name}");
            assert!(main(&root, &Args { write: true }).is_err(), "{name}");
        }
        let root = documented("no-doc", EMPTY_DOC);
        fs::remove_file(root.join(DOC)).unwrap();
        assert_eq!(check(&root).unwrap().problems.len(), 1);
        assert!(main(&root, &Args { write: true }).is_err());
        // The layering's own problem is still reported beside the missing description.
        let specs = [krate("vm", "L1", ON_C), krate("c", "L3", "")];
        let root = workspace("undescribed", &specs, "");
        fs::create_dir_all(root.join("docs")).unwrap();
        fs::write(root.join(DOC), EMPTY_DOC).unwrap();
        let found = check(&root).unwrap().problems;
        assert_eq!(found.len(), 2, "{found:?}");
        assert!(
            found[0].starts_with("vm (L1) depends on c (L3)"),
            "{found:?}"
        );
        assert!(found[1].contains("no description"), "{found:?}");
    }

    #[test]
    fn a_description_stays_in_its_cell() {
        let specs = [krate(
            "a",
            "L0",
            "description = \"\"\"Reads BSP29 | BSP2,\nand more\"\"\"\n",
        )];
        let root = workspace("cell", &specs, "");
        assert_eq!(
            table(&root).unwrap().lines().last(),
            Some("| L0 | `a` | Reads BSP29 \\| BSP2, and more |")
        );
    }

    #[test]
    fn the_repository_layering_passes() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        assert_eq!(check(root).unwrap().problems, Vec::<String>::new());
    }
}
