//! `cargo xtask keymap [--check]`: writes `docs/keymap.md`, every command with its default
//! key, where the key is taken and what it follows, from the command registry and
//! `qs-layout`'s key tables (UI-21, MAP-20, P7-17); `--check` writes nothing and fails when the
//! checked-in file differs. Either way it fails when a command of the registry is in neither
//! table, a table names a command the registry lacks, or a keyed command needs a parameter a
//! key cannot give. `cargo xtask ci` runs the check in-process ([`check`]).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use qs_commands::Registry;
use qs_layout::{DEFAULT_KEYS, Follows, KeyContext, UNKEYED, Unkeyed};

use crate::commands::registry;
use crate::{Report, print_outcome};

/// The keymap, relative to the workspace root.
pub(crate) const KEYMAP: &str = "docs/keymap.md";

/// `cargo xtask keymap [--check]`.
#[derive(clap::Parser, Debug)]
pub(crate) struct Args {
    /// Check the keymap instead of writing it.
    #[arg(long)]
    check: bool,
}

/// Runs `cargo xtask keymap` with the arguments `args`.
pub(crate) fn main(root: &Path, args: &Args) -> Result<bool, String> {
    if args.check {
        return Ok(print_outcome("keymap", check(root)));
    }
    let registry = registry()?;
    let problems = problems(&registry);
    if !problems.is_empty() {
        return Err(problems.join("; "));
    }
    fs::write(root.join(KEYMAP), keymap(&registry)).map_err(|e| format!("{KEYMAP}: {e}"))?;
    eprintln!("keymap: wrote {KEYMAP}");
    Ok(true)
}

/// Checks that every command is keyed or says why not, and that `docs/keymap.md` is what the
/// tables render.
pub(crate) fn check(root: &Path) -> Result<Report, String> {
    let registry = registry()?;
    let mut report = Report::default();
    let problems = problems(&registry);
    report.record(
        problems.is_empty(),
        if problems.is_empty() {
            "every command has a default key or a reason for none".to_owned()
        } else {
            problems.join("; ")
        },
    );
    let current = fs::read_to_string(root.join(KEYMAP)).map_err(|e| format!("{KEYMAP}: {e}"))?;
    let matches = current == keymap(&registry);
    report.record(
        matches,
        if matches {
            format!("{KEYMAP} matches the key tables")
        } else {
            format!("{KEYMAP} differs from the key tables; run cargo xtask keymap")
        },
    );
    Ok(report)
}

/// What is wrong between `registry` and the key tables: a command in neither, a table's command
/// the registry lacks, and a keyed command that needs a parameter.
fn problems<C: 'static>(registry: &Registry<C>) -> Vec<String> {
    let mut problems = Vec::new();
    let listed: BTreeMap<&str, bool> = DEFAULT_KEYS
        .iter()
        .map(|key| (key.command, true))
        .chain(UNKEYED.iter().map(|(command, _)| (*command, false)))
        .collect();
    for info in registry.commands() {
        let id = info.id().as_str();
        match listed.get(id) {
            None => problems.push(format!(
                "{id} has no default key and no reason for none (crates/qs-layout/src/keys.rs)"
            )),
            Some(true) if needs_a_value(info.params()) => {
                problems.push(format!("{id} has a key but needs a parameter"));
            }
            Some(_) => {}
        }
    }
    for id in listed.keys() {
        if registry.get(id).is_none() {
            problems.push(format!("{id} is in the key tables but is no command"));
        }
    }
    problems
}

/// Whether a command's parameter schema requires a value.
fn needs_a_value(params: &serde_json::Value) -> bool {
    params
        .get("required")
        .and_then(serde_json::Value::as_array)
        .is_some_and(|required| !required.is_empty())
}

/// The keymap as Markdown.
fn keymap<C: 'static>(registry: &Registry<C>) -> String {
    let mut out = String::from(
        "<!-- Generated by `cargo xtask keymap` from the command registry and \
         crates/qs-layout/src/keys.rs. Do not edit by hand. -->\n\n# Keymap\n\n\
         Every command's default key (UI-21). A key follows TrenchBroom's default where \
         TrenchBroom binds the same action (MAP-20), named as its `ActionManager.cpp` names it \
         at TrenchBroom/TrenchBroom@8f329f11e65e3d21b355a42bcae199cb3e4e0812; otherwise the \
         choice is ours and the table says why. `secondary` is Cmd on macOS and Ctrl elsewhere. \
         A key is changed in the keymap file (`docs/commands.md` lists the commands).\n\n\
         ## Keys\n\n| Command | Keys | Where | Follows |\n| --- | --- | --- | --- |\n",
    );
    for key in &DEFAULT_KEYS {
        let context = match key.context {
            KeyContext::Window => "anywhere",
            KeyContext::Shell => "outside the code editor",
            KeyContext::Map => "in the map view",
        };
        let follows = match key.follows {
            Follows::TrenchBroom(action) => format!("TrenchBroom's `{action}`"),
            Follows::Own(why) => format!("ours: {why}"),
        };
        writeln!(
            out,
            "| `{}` | `{}` | {context} | {follows} |",
            key.command,
            key.keys.replace('|', "\\|")
        )
        .ok();
    }
    out.push_str(
        "\n## Commands with no key\n\nA command that answers a question is read by a panel, \
         the agent or MCP. A command the window runs itself is a poll or a hand-over. A command \
         that needs a value, a path, a name or a place, runs from the command line, which asks \
         for each, or from the control in the window that has the value.\n\n\
         | Command | Why | Summary |\n| --- | --- | --- |\n",
    );
    for (command, why) in &UNKEYED {
        let why = match why {
            Unkeyed::Query => "answers a question",
            Unkeyed::Window => "run by the window",
            Unkeyed::Typed => "needs a value",
        };
        let summary = registry
            .get(command)
            .map(|info| info.summary().replace('|', "\\|"))
            .unwrap_or_default();
        writeln!(out, "| `{command}` | {why} | {summary} |").ok();
    }
    out
}

#[cfg(test)]
mod tests {
    #![expect(
        clippy::unwrap_used,
        reason = "test code: a failed unwrap is a failed test"
    )]

    use super::*;
    use crate::test_dirs;

    // No spec statement: UI-21, #971: every command of the registry has a default key or a
    // reason for none, and no key is given to a command that needs a parameter
    #[test]
    fn every_command_is_keyed_or_says_why_not() {
        let registry = registry().unwrap();
        assert_eq!(problems(&registry), Vec::<String>::new());
        // A registry without the commands the tables name is reported.
        let bare = Registry::<()>::new();
        assert!(!problems(&bare).is_empty());
    }

    // No spec statement: UI-21, #971: every command of the registry runs from the command line:
    // named by its id it asks for each of its parameters in turn, and with a value for each it
    // makes the command with every parameter its schema requires
    #[test]
    fn every_command_runs_from_the_command_line() {
        use qs_commands::line::{CommandLine, Entered};
        use qs_commands::params::FieldKind;
        let registry = registry().unwrap();
        for info in registry.commands() {
            let id = info.id().as_str();
            let mut line = CommandLine::new();
            let mut entered = line.enter(&registry, id);
            let mut asked = 0_usize;
            while let Entered::Ask(prompt) = &entered {
                asked += 1;
                assert_eq!(prompt.command, id);
                assert_eq!(prompt.place.0, asked, "{id} asks in turn");
                // A value of the kind asked for; an optional one is left to its default.
                let typed = match &prompt.field.kind {
                    _ if !prompt.field.required => String::new(),
                    FieldKind::Choice(choices) => match choices.first().map(|c| &c.value) {
                        Some(serde_json::Value::String(text)) => text.clone(),
                        Some(other) => other.to_string(),
                        None => String::new(),
                    },
                    FieldKind::Text => "x".to_owned(),
                    FieldKind::Number | FieldKind::Integer => "1".to_owned(),
                    FieldKind::Boolean => "yes".to_owned(),
                    FieldKind::Json => "[]".to_owned(),
                };
                entered = line.enter(&registry, &typed);
            }
            let ran = matches!(&entered, Entered::Run { id: made, .. } if made == id);
            assert!(ran, "{id} did not run: {entered:?}");
            let Entered::Run { params, .. } = entered else {
                continue;
            };
            let required = info
                .params()
                .get("required")
                .and_then(serde_json::Value::as_array)
                .cloned()
                .unwrap_or_default();
            for name in required {
                let name = name.as_str().unwrap();
                assert!(params.get(name).is_some(), "{id} lacks {name}");
            }
        }
    }

    #[test]
    fn writing_then_checking_passes_and_an_edit_fails_the_check() {
        let root = test_dirs::fresh("keymap");
        fs::create_dir_all(root.join("docs")).unwrap();
        assert!(check(&root).unwrap_err().contains(KEYMAP));
        assert_eq!(main(&root, &Args { check: false }), Ok(true));
        assert!(check(&root).unwrap().problems.is_empty());
        let path = root.join(KEYMAP);
        let edited = fs::read_to_string(&path)
            .unwrap()
            .replace("secondary-z", "secondary-y");
        fs::write(&path, edited).unwrap();
        assert_eq!(check(&root).unwrap().problems.len(), 1);
        assert_eq!(main(&root, &Args { check: true }), Ok(false));
    }
}
