// spec QC-25.1: statement 0, function 0, global and field definition 0 and string 0 are
// placeholders.
#[test]
fn every_table_starts_with_a_placeholder() {
    let p = progs(".float fl;\nvoid() f = {};\n");
    assert_eq!(p.statements[0], Statement::default());
    assert_eq!(p.functions[0], Function::default());
    assert_eq!(p.global_defs[0], Def::default());
    assert_eq!(p.field_defs[0], Def::default());
    assert_eq!(p.strings[0], 0);
    let bytes = qc_progs::write(&p).unwrap();
    assert_eq!(&bytes[..4], &6_i32.to_le_bytes(), "version 6");
}

// spec QC-25.2: functions are numbered in the order their definitions end, from 1; a
// prototype makes none.
#[test]
fn functions_are_numbered_as_their_definitions_end() {
    let p = progs("void() b;\nvoid() a = { b(); };\nvoid() b = {};\nvoid() c = #3;\n");
    let names: Vec<String> = p.functions[1..]
        .iter()
        .map(|f| string(&p, f.s_name))
        .collect();
    assert_eq!(names, ["a", "b", "c"]);
    let b = usize::try_from(global(&p, "b")).unwrap();
    assert_eq!(
        p.globals[b].bits(),
        2,
        "b's global holds its function number"
    );
}

// spec QC-25.3: one global definition per definition in the order made, parameters, locals,
// components and literals included, temporaries not; a field is also in the field table, with
// the type it holds.
#[test]
fn the_definition_tables() {
    let p = progs(".vector fv;\nfloat a;\nvoid(float x) f = { local float y; a = x + 1; };\n");
    let names: Vec<String> = p.global_defs[1..]
        .iter()
        .map(|d| string(&p, d.s_name))
        .collect();
    assert_eq!(
        names,
        [
            "fv",
            "fv_x",
            "fv_y",
            "fv_z",
            "a",
            "f",
            "x",
            "y",
            "IMMEDIATE"
        ]
    );
    let fields: Vec<(String, u32, u32)> = p.field_defs[1..]
        .iter()
        .map(|d| (string(&p, d.s_name), d.type_bits, d.ofs))
        .collect();
    assert_eq!(
        fields,
        [
            ("fv".to_owned(), 3, 0),
            ("fv_x".to_owned(), 2, 0),
            ("fv_y".to_owned(), 2, 1),
            ("fv_z".to_owned(), 2, 2)
        ]
    );
    assert_eq!(
        p.global_defs[1].type_bits, 5,
        "a field's global is of type field"
    );
}

// spec QC-25.4: strings are appended as met, never shared: the file's name, the literals, each
// function's name when its definition ends; then each definition's name, a field's twice; the
// table is padded to a multiple of 4.
#[test]
fn the_string_table_in_order() {
    let compiled = compile_source(".float fl;\nstring s;\nvoid() f = { s = \"lit\"; };\n").unwrap();
    let p = compiled.progs;
    let text: Vec<&[u8]> = p.strings.split(|&b| b == 0).collect();
    assert_eq!(
        &text[..9],
        [
            &b""[..],
            b"t.qc",
            b"lit",
            b"f",
            b"fl",
            b"fl",
            b"s",
            b"f",
            b"IMMEDIATE"
        ]
    );
    assert_eq!(p.strings.len() % 4, 0);
}

// spec QC-25.4, QC-27.17: each file's name is copied when it starts, as `progs.src` lists it.
#[test]
fn each_file_records_its_name() {
    let p = compile_files(&[
        ("a.qc", "void() f = {};\n"),
        ("sub/b.qc", "void() g = {};\n"),
    ])
    .unwrap()
    .progs;
    let file = |name: &str| {
        let f = p
            .functions
            .iter()
            .find(|f| string(&p, f.s_name) == name)
            .unwrap();
        string(&p, f.s_file)
    };
    assert_eq!(file("f"), "a.qc");
    assert_eq!(file("g"), "sub/b.qc");
}

// spec QC-25.5, QC-25.6: progdefs.h declares the globals before `end_sys_globals` and the
// fields before `end_sys_fields`, typed; the header CRC is the CRC of that text before its
// `#define` line.
#[test]
fn progdefs_and_its_crc() {
    let compiled = compile_source(
        "float time;\nvector origin;\nentity self;\nstring mapname;\nvoid() main;\n\
         float end_sys_globals;\n.float health;\n.vector angles;\n.string model;\n\
         .void() think;\n.float end_sys_fields;\n.float other;\nvoid() main = {};\n",
    )
    .unwrap();
    let want = "\n/* file generated by qcc, do not modify */\n\ntypedef struct\n{\tint\tpad[28];\n\
                \tfloat\ttime;\n\tvec3_t\torigin;\n\tint\tself;\n\tstring_t\tmapname;\n\
                \tfunc_t\tmain;\n} globalvars_t;\n\ntypedef struct\n{\n\tfloat\thealth;\n\
                \tvec3_t\tangles;\n\tstring_t\tmodel;\n\tfunc_t\tthink;\n} entvars_t;\n\n";
    assert_eq!(
        compiled.progdefs,
        format!(
            "{want}#define PROGHEADER_CRC {}\n",
            crc_block(want.as_bytes())
        )
    );
    assert_eq!(compiled.crc, crc_block(want.as_bytes()));
    assert_eq!(compiled.progs.crc, i32::from(compiled.crc));
}

// spec QC-25.7, QC-27.13: a vector literal before `end_sys_globals` has no components, and
// progdefs.h skips none after it, where id's qcc skips the next three definitions.
#[test]
fn a_vector_literal_skips_no_definitions() {
    let compiled =
        compile_source("vector v;\nvoid() f = { v = '1 2 3'; };\nfloat x, y, z;\n").unwrap();
    assert!(
        compiled
            .progdefs
            .contains("\tvec3_t\tv;\n\tfunc_t\tf;\n\tvec3_t\tIMMEDIATE;\n")
    );
    assert!(
        compiled
            .progdefs
            .contains("\tfloat\tx;\n\tfloat\ty;\n\tfloat\tz;\n")
    );
}

