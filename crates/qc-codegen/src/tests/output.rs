// spec QC-26.1, QC-26.2: a call of a `precache_sound`, `precache_model` or `precache_file`
// function adds its first argument's string once, in the block the byte after the prefix
// names.
#[test]
fn precache_calls_are_listed() {
    let compiled = compile_source(
        "void(string s) precache_sound = #19;\nvoid(string s) precache_sound2 = #19;\n\
         void(string s) precache_model = #20;\nvoid(string s) precache_file = #68;\n\
         void(string s) precache_filex = #68;\n\
         void() f = { precache_sound(\"a.wav\"); precache_sound(\"a.wav\"); \
         precache_sound2(\"b.wav\"); precache_model(\"m.mdl\"); precache_file(\"f\"); \
         precache_filex(\"g\"); };\n",
    )
    .unwrap();
    let list = |names: &[(&str, u8)]| -> Vec<Precache> {
        names
            .iter()
            .map(|(n, block)| Precache {
                name: n.as_bytes().to_vec(),
                block: *block,
            })
            .collect()
    };
    assert_eq!(
        compiled.precaches.sounds,
        list(&[("a.wav", 1), ("b.wav", 2)])
    );
    assert_eq!(compiled.precaches.models, list(&[("m.mdl", 1)]));
    assert_eq!(compiled.precaches.files, list(&[("f", 1), ("g", 1)]));
}

// spec QC-26.3, QC-26.5: a first argument that is not a constant adds its compile-time value,
// the empty string of a variable; one whose word is no string offset adds nothing.
#[test]
fn a_variable_precache_adds_its_compile_time_value() {
    let compiled = compile_source(
        "void(string s) precache_sound = #19;\nvoid(float s) precache_model = #20;\nstring t;\n\
         void() f = { precache_sound(t); precache_model(1000000); };\n",
    )
    .unwrap();
    assert_eq!(
        compiled.precaches.sounds,
        [Precache {
            name: Vec::new(),
            block: 1
        }]
    );
    assert!(compiled.precaches.models.is_empty());
}

// spec QC-26.4: the model list is not bounded by the sound count's limit check, in this
// compiler not bounded at all (LIMIT-7.3).
#[test]
fn many_models_are_listed() {
    let mut source = String::from("void(string s) precache_model = #20;\nvoid() f = {\n");
    for i in 0..1100 {
        source.push_str(&format!("precache_model(\"m{i}\");\n"));
    }
    source.push_str("};\n");
    assert_eq!(
        compile_source(&source).unwrap().precaches.models.len(),
        1100
    );
}

