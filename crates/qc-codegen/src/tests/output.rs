// spec QC-27.19: every statement has the line of the source statement it was emitted for, a
// state header's and an empty body's the line of the function's name; statement 0 has none;
// the map's counts are the progs'
#[test]
fn every_statement_maps_to_its_source_line() {
    let source =
        "float a;\nvoid() g;\nvoid() f = [1, g]\n{\n\ta = 1;\n\n\tg();\n};\nvoid() g = {};\n";
    let compiled = compile_source(source).unwrap();
    let p = &compiled.progs;
    let lno = &compiled.lno;
    assert_eq!(lno.lines.len(), p.statements.len());
    assert_eq!(lno.lines[0], 0);
    assert!(
        lno.lines[1..].iter().all(|&line| line > 0),
        "{:?}",
        lno.lines
    );
    let first = |name: &str| {
        let f = p
            .functions
            .iter()
            .find(|f| string(p, f.s_name) == name)
            .unwrap();
        usize::try_from(f.first_statement).unwrap()
    };
    let f = first("f");
    // `STATE`, then `a = 1;` on line 5, then the call on line 7 and the `DONE` after it.
    assert_eq!(&lno.lines[f..f + 4], [3, 5, 7, 7]);
    assert_eq!(
        lno.lines[first("g")],
        9,
        "an empty body's DONE is on the name's line"
    );
    let bytes = qc_progs::write(p).unwrap();
    let unchecked = qc_progs::ReadOptions {
        check_header_crc: false,
    };
    let header = *qc_progs::Progs::read_with(&bytes, &unchecked)
        .unwrap()
        .header();
    assert_eq!(lno.matches_header(&header), Ok(()));
}

fn with_statement(statement: Statement) -> ProgsFile {
    ProgsFile {
        statements: vec![Statement::default(), statement],
        ..ProgsFile::default()
    }
}

// spec FTE-24.1: FTEQCC writes the 32-bit layout for more than 65530 globals or a GOTO past
// 0x7fff, and tests no IF's offset
#[test]
fn a_big_program_takes_the_32_bit_layout() {
    let goto = u32::from(Opcode::Goto.number());
    let if_op = u32::from(Opcode::If.number());
    let jump = |op, a, b| with_statement(Statement { op, a, b, c: 0 });
    assert!(!needs_fte32(&jump(goto, 0x7fff, 0)));
    assert!(!needs_fte32(&jump(goto, -0x7fff, 0)));
    assert!(needs_fte32(&jump(goto, 0x8000, 0)));
    assert!(needs_fte32(&jump(goto, -0x8000, 0)));
    assert!(!needs_fte32(&jump(if_op, 0x8000, 0x8000)));
    let mut globals = ProgsFile {
        globals: vec![Slot::from_bits(0); 65530],
        ..ProgsFile::default()
    };
    assert!(!needs_fte32(&globals));
    globals.globals.push(Slot::from_bits(0));
    assert!(needs_fte32(&globals));
}

// spec FTE-24.2: a version 6 operand from 32768 to 65535 is written as its low 16 bits
#[test]
fn a_global_past_32767_is_written_as_its_low_bits() {
    let mut p = with_statement(Statement {
        op: 1,
        a: 0x7fff,
        b: 0x8000,
        c: 0xffff,
    });
    wrap_short_operands(&mut p);
    assert_eq!(
        (p.statements[1].a, p.statements[1].b, p.statements[1].c),
        (0x7fff, -0x8000, -1)
    );
    let mut negative = with_statement(Statement {
        op: 1,
        a: -5,
        b: 0x1_0000,
        c: 0,
    });
    wrap_short_operands(&mut negative);
    assert_eq!(
        (negative.statements[1].a, negative.statements[1].b),
        (-5, 0x1_0000)
    );
    assert!(qc_progs::write(&p).is_ok());
}
