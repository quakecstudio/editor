/// `PR_WriteProgdefs` (QC-25.5, QC-25.6): the text of `progdefs.h` and the CRC of it up to the
/// `#define` line, which is appended with that CRC.
///
/// The globals before the one named `end_sys_globals` become `globalvars_t`, the fields before
/// the one named `end_sys_fields` become `entvars_t`, each typed by its QuakeC type. A vector's
/// component definitions are skipped after it, where `qcc` skips the next three definitions
/// whatever they are, past the end of the list after a literal (QC-25.7, QC-27.13).
pub(crate) fn progdefs(program: &Program) -> (String, u16) {
    let mut text = String::new();
    _ = writeln!(
        text,
        "\n/* file generated by qcc, do not modify */\n\ntypedef struct\n{{\tint\tpad[{RESERVED_OFS}];"
    );
    let mut defs = program.defs.iter().peekable();
    while let Some(def) = defs.next() {
        if def.name == "end_sys_globals" {
            break;
        }
        let etype = def.ty.etype();
        _ = writeln!(text, "\t{}\t{};", c_type(etype), def.name);
        if etype == Etype::Vector {
            skip_components(def, &mut defs);
        }
    }
    text.push_str("} globalvars_t;\n\n");
    text.push_str("typedef struct\n{\n");
    let mut defs = program.defs.iter().peekable();
    while let Some(def) = defs.next() {
        if def.name == "end_sys_fields" {
            break;
        }
        let Some(inner) = def.ty.field_inner() else {
            continue;
        };
        let etype = inner.etype();
        _ = writeln!(text, "\t{}\t{};", c_type(etype), def.name);
        if etype == Etype::Vector {
            skip_components(def, &mut defs);
        }
    }
    text.push_str("} entvars_t;\n\n");
    let crc = crc_block(&latin1_encode(&text));
    _ = writeln!(text, "#define PROGHEADER_CRC {crc}");
    (text, crc)
}

/// The C type `PR_WriteProgdefs` writes for a definition of basic type `etype` (QC-25.5).
const fn c_type(etype: Etype) -> &'static str {
    match etype {
        Etype::Float => "float",
        Etype::Vector => "vec3_t",
        Etype::String => "string_t",
        Etype::Function => "func_t",
        Etype::Entity | Etype::Void | Etype::Field | Etype::Pointer => "int",
    }
}

/// Skips the definitions after vector `def` that are its components, `_x`, `_y` and `_z` in
/// order (QC-27.13).
fn skip_components<'d>(def: &Def, defs: &mut std::iter::Peekable<impl Iterator<Item = &'d Def>>) {
    for suffix in ["_x", "_y", "_z"] {
        let name = format!("{}{suffix}", def.name);
        if defs.next_if(|next| next.name == name).is_none() {
            return;
        }
    }
}

/// `WriteData` (QC-25.1 to QC-25.4): the progs.dat tables in `qcc`'s layout, with header CRC
/// `crc`.
///
/// Every definition of the list goes to the global definitions table, a field also to the field
/// table first, each name copied to the string table again (QC-25.3, QC-25.4). A global is
/// marked to be saved when it is not initialised, not a function or field and not local
/// (QC-21.6). The string table is padded to a multiple of 4 (QC-25.4).
/// FTE-24.1: whether FTEQCC writes `progs` in the 32-bit layout, for more than 65530 globals or
/// a `GOTO` offset past `0x7fff`.
pub(crate) fn needs_fte32(progs: &ProgsFile) -> bool {
    const FTE32_GLOBALS: usize = 65530;
    const BIG_JUMP: i32 = 0x7fff;
    let goto = u32::from(Opcode::Goto.number());
    progs.globals.len() > FTE32_GLOBALS
        || progs
            .statements
            .iter()
            .any(|statement| statement.op == goto && !(-BIG_JUMP..=BIG_JUMP).contains(&statement.a))
}

/// FTE-13.13: the records of the array element `name` of type `ty` at `ofs`: its own, a struct
/// element's typed `ev_struct`, then each member's that starts at a word, `name.member`, an
/// array member as one record.
fn element_records(
    out: &mut Vec<DefRecord>,
    program: &mut Program,
    index: &ModuleIndex,
    (name, ty, ofs): (&str, &ValueType, u32),
    saving: Saving,
) -> Result<(), Internal> {
    let shape = match ty {
        ValueType::Of(t) => index.struct_shape(t),
        ValueType::FloatField => None,
    };
    // `def->saved = false; //struct headers don't get saved.`
    let type_bits = if shape.is_some() {
        EV_STRUCT
    } else {
        saving.bits(type_number(index, ty))
    };
    out.push(DefRecord {
        type_bits,
        ofs,
        s_name: program.copy_string(&latin1_encode(name))?,
    });
    if let Some(shape) = shape {
        member_records(out, program, name, (index, shape), (ofs, saving))?;
    }
    Ok(())
}

/// Whether a global's records are written saved, `DEF_SAVEGLOBAL` (QC-25.3, FTEF-19.82).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Saving {
    /// The engine saves and restores the global.
    Saved,
    /// It does not.
    Unsaved,
}

impl Saving {
    /// The type of a record whose type number is `number`: saved unless it is a field's
    /// (`def->type->type != ev_field`).
    fn bits(self, number: u16) -> u32 {
        match self {
            Self::Saved if number != Etype::Field.number() => {
                u32::from(number) | PROGS_DEF_SAVEGLOBAL
            }
            Self::Saved | Self::Unsaved => u32::from(number),
        }
    }
}

/// FTE-13.13: the records of the members of the struct value `name` at `ofs`, `name.member`,
/// each member that starts at a word, an array member as one record.
fn member_records(
    out: &mut Vec<DefRecord>,
    program: &mut Program,
    name: &str,
    (index, shape): (&ModuleIndex, &StructShape),
    (ofs, saving): (u32, Saving),
) -> Result<(), Internal> {
    for member in &shape.members {
        let at = ofs.checked_add(member.word).ok_or(Internal::TooLarge)?;
        // A member that is itself a struct is its header, which is never saved.
        let saving = match index.struct_shape(&member.ty) {
            Some(_) => Saving::Unsaved,
            None => saving,
        };
        out.push(DefRecord {
            type_bits: saving.bits(type_number(index, &ValueType::Of(member.ty.clone()))),
            ofs: at,
            s_name: program.copy_string(&latin1_encode(&format!("{name}.{}", member.name)))?,
        });
    }
    Ok(())
}

/// FTE-24.2: each version 6 operand from 32768 to 65535 as the `short` its low 16 bits are.
pub(crate) fn wrap_short_operands(progs: &mut ProgsFile) {
    const SHORT_SPAN: i32 = 0x1_0000;
    for statement in &mut progs.statements {
        for operand in [&mut statement.a, &mut statement.b, &mut statement.c] {
            if (0x8000..SHORT_SPAN).contains(operand) {
                *operand = operand.wrapping_sub(SHORT_SPAN);
            }
        }
    }
}

/// FTE-24.3: each operand of version 7's 16-bit layout as the `unsigned short` its low 16 bits
/// are, so a jump's negative offset is written as 65536 plus it, as FTEQCC's
/// `(unsigned short)PRLittleShort((unsigned short)a)` writes it.
pub(crate) fn wrap_unsigned_operands(progs: &mut ProgsFile) {
    const SHORT_SPAN: i32 = 0x1_0000;
    /// The least `short`, the lowest operand a 16-bit statement holds.
    const SHORT_MIN: i32 = -0x8000;
    for statement in &mut progs.statements {
        for operand in [&mut statement.a, &mut statement.b, &mut statement.c] {
            if (SHORT_MIN..0).contains(operand) {
                *operand = operand.wrapping_add(SHORT_SPAN);
            }
        }
    }
}

/// How the global definition list is written (FTE-13.13).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Records {
    /// A record for each definition, as id's `qcc` writes them.
    Qcc,
    /// As FTEQCC writes them: an array's or a struct's head left out, for a record for each
    /// element, a struct element's members after it, or for each of a struct's members.
    Fteqcc,
}

/// FTEQCC's `ev_struct`, the type an element of an array of structs is written with
/// (`progslib.h`'s `etype_t`).
const EV_STRUCT: u32 = 14;

pub(crate) fn progs(
    mut program: Program,
    crc: u16,
    index: &ModuleIndex,
    records: Records,
) -> Result<ProgsFile, Internal> {
    let mut global_defs = vec![DefRecord::default()];
    let mut field_defs = vec![DefRecord::default()];
    let defs = std::mem::take(&mut program.defs);
    for def in &defs {
        let etype = def.ty.etype();
        // FTE-13.14: FTEQCC writes a field's definition only for a constant at file level or
        // initialised, so a parameter of a field type makes none.
        let field_record =
            records == Records::Qcc || (def.constant && (def.scope.is_none() || def.initialized));
        if let Some(inner) = def.ty.field_inner().filter(|_| field_record) {
            field_defs.push(DefRecord {
                type_bits: u32::from(type_number(index, &inner)),
                ofs: program.word(def.ofs),
                s_name: program.copy_string(&latin1_encode(&def.name))?,
            });
        }
        // QC-25.3: id's `qcc` saves a global with no initial value. FTEF-19.82: FTEQCC saves a
        // global it is asked to save, `def->saved`, that it does not hold constant; each record
        // of it but a field's.
        let asked = match records {
            Records::Qcc => !def.initialized && etype != Etype::Function,
            Records::Fteqcc => def.id.is_some_and(|id| index.is_saved(id)) && !def.constant,
        } && def.scope.is_none();
        let saving = if asked {
            Saving::Saved
        } else {
            Saving::Unsaved
        };
        if records == Records::Fteqcc
            && let Some(count) = def.count
        {
            let words = type_words(index, &def.ty);
            for i in 0..count {
                let ofs = i
                    .checked_mul(words)
                    .and_then(|w| w.checked_add(def.ofs))
                    .ok_or(Internal::TooLarge)?;
                let name = format!("{}[{i}]", def.name);
                let element = (name.as_str(), &def.ty, ofs);
                element_records(&mut global_defs, &mut program, index, element, saving)?;
            }
            continue;
        }
        if records == Records::Fteqcc
            && let ValueType::Of(t) = &def.ty
            && let Some(shape) = index.struct_shape(t)
        {
            member_records(
                &mut global_defs,
                &mut program,
                &def.name,
                (index, shape),
                (def.ofs, saving),
            )?;
            continue;
        }
        global_defs.push(DefRecord {
            type_bits: saving.bits(type_number(index, &def.ty)),
            ofs: def.ofs,
            s_name: program.copy_string(&latin1_encode(&def.name))?,
        });
    }
    let mut strings = program.strings;
    let padded = strings
        .len()
        .checked_add(3)
        .map(|n| n & !3)
        .ok_or(Internal::TooLarge)?;
    strings.resize(padded, 0);
    Ok(ProgsFile {
        crc: i32::from(crc),
        entityfields: i32::try_from(program.size_fields).map_err(|_| Internal::TooLarge)?,
        statements: program.statements,
        global_defs,
        field_defs,
        functions: program.functions,
        strings,
        globals: program.globals.into_iter().map(Slot::from_bits).collect(),
        ..ProgsFile::default()
    })
}
