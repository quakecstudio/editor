//! The program's output (QC-25): `progdefs.h`, whose CRC the progs header carries, and the
//! progs.dat tables `WriteData` writes.

use qc_progs::crc::crc_block;
use qc_progs::{Def as DefRecord, PROGS_DEF_SAVEGLOBAL, ProgsFile};
use qc_types::{Etype, Slot};

use crate::Internal;
use crate::compile::latin1;
use crate::program::{Def, Program, RESERVED_OFS};

/// `PR_WriteProgdefs` (QC-25.5, QC-25.6): the text of `progdefs.h` and the CRC of it up to the
/// `#define` line, which is appended with that CRC.
///
/// The globals before the one named `end_sys_globals` become `globalvars_t`, the fields before
/// the one named `end_sys_fields` become `entvars_t`, each typed by its QuakeC type. A vector's
/// component definitions are skipped after it, where `qcc` skips the next three definitions
/// whatever they are, past the end of the list after a literal (QC-25.7, QC-27.13).
pub(crate) fn progdefs(program: &Program) -> (String, u16) {
    let mut text = String::new();
    text.push_str(&format!(
        "\n/* file generated by qcc, do not modify */\n\ntypedef struct\n{{\tint\tpad[{RESERVED_OFS}];\n"
    ));
    let mut defs = program.defs.iter().peekable();
    while let Some(def) = defs.next() {
        if def.name == "end_sys_globals" {
            break;
        }
        let etype = def.ty.etype();
        text.push_str(&format!("\t{}\t{};\n", c_type(etype), def.name));
        if etype == Etype::Vector {
            skip_components(def, &mut defs);
        }
    }
    text.push_str("} globalvars_t;\n\n");
    text.push_str("typedef struct\n{\n");
    let mut defs = program.defs.iter().peekable();
    while let Some(def) = defs.next() {
        if def.name == "end_sys_fields" {
            break;
        }
        let Some(inner) = def.ty.field_inner() else {
            continue;
        };
        let etype = inner.etype();
        text.push_str(&format!("\t{}\t{};\n", c_type(etype), def.name));
        if etype == Etype::Vector {
            skip_components(def, &mut defs);
        }
    }
    text.push_str("} entvars_t;\n\n");
    let crc = crc_block(&latin1(&text));
    text.push_str(&format!("#define PROGHEADER_CRC {crc}\n"));
    (text, crc)
}

/// The C type `PR_WriteProgdefs` writes for a definition of basic type `etype` (QC-25.5).
const fn c_type(etype: Etype) -> &'static str {
    match etype {
        Etype::Float => "float",
        Etype::Vector => "vec3_t",
        Etype::String => "string_t",
        Etype::Function => "func_t",
        Etype::Entity | Etype::Void | Etype::Field | Etype::Pointer => "int",
    }
}

/// Skips the definitions after vector `def` that are its components, `_x`, `_y` and `_z` in
/// order (QC-27.13).
fn skip_components<'d>(def: &Def, defs: &mut std::iter::Peekable<impl Iterator<Item = &'d Def>>) {
    for suffix in ["_x", "_y", "_z"] {
        let name = format!("{}{suffix}", def.name);
        if defs.next_if(|next| next.name == name).is_none() {
            return;
        }
    }
}

/// `WriteData` (QC-25.1 to QC-25.4): the progs.dat tables in `qcc`'s layout, with header CRC
/// `crc`.
///
/// Every definition of the list goes to the global definitions table, a field also to the field
/// table first, each name copied to the string table again (QC-25.3, QC-25.4). A global is
/// marked to be saved when it is not initialised, not a function or field and not local
/// (QC-21.6). The string table is padded to a multiple of 4 (QC-25.4).
pub(crate) fn progs(mut program: Program, crc: u16) -> Result<ProgsFile, Internal> {
    let mut global_defs = vec![DefRecord::default()];
    let mut field_defs = vec![DefRecord::default()];
    let defs = std::mem::take(&mut program.defs);
    for def in &defs {
        let etype = def.ty.etype();
        if let Some(inner) = def.ty.field_inner() {
            field_defs.push(DefRecord {
                type_bits: u32::from(inner.etype().number()),
                ofs: program.word(def.ofs),
                s_name: program.copy_string(&latin1(&def.name))?,
            });
        }
        let saved = !def.initialized
            && etype != Etype::Function
            && etype != Etype::Field
            && def.scope.is_none();
        let mut type_bits = u32::from(etype.number());
        if saved {
            type_bits |= PROGS_DEF_SAVEGLOBAL;
        }
        global_defs.push(DefRecord {
            type_bits,
            ofs: def.ofs,
            s_name: program.copy_string(&latin1(&def.name))?,
        });
    }
    let mut strings = program.strings;
    let padded = strings
        .len()
        .checked_add(3)
        .map(|n| n & !3)
        .ok_or(Internal::TooLarge)?;
    strings.resize(padded, 0);
    Ok(ProgsFile {
        crc: i32::from(crc),
        entityfields: i32::try_from(program.size_fields).map_err(|_| Internal::TooLarge)?,
        statements: program.statements,
        global_defs,
        field_defs,
        functions: program.functions,
        strings,
        globals: program.globals.into_iter().map(Slot).collect(),
        ..ProgsFile::default()
    })
}
