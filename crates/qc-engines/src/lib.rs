//! The engine-target database: which builtins and extensions each Quake engine supports.
//!
//! A QuakeC builtin is a function the engine implements, declared in QuakeC as `= #N`; the
//! number is the only link between the progs and the engine, and which numbers an engine has
//! differs from engine to engine and, within one engine, from module kind to module kind
//! (server, client and menu QuakeC). This crate holds builtin tables and extension lists for
//! seven engines ([`Engine`]), one per module kind a fact source covers, so the editor, the
//! compiler and the agent know what a target supports (LANG-6, AGT-9), and [`check`] reports
//! a call of a builtin the target lacks (PRIN-8).
//!
//! The tables of QuakeSpasm, Ironwail, vkQuake, FTEQW, DarkPlaces and the 2021 rerelease are
//! generated by `cargo xtask engines` from ten fact sources pinned by commit and SHA-256 in
//! `sources.toml` ([`SOURCES`]); only facts are extracted, and ADR-0015 and ADR-0016 record
//! the legal basis. The vanilla table is `qc-builtins`', ported from id's engine.
//!
//! # Layer
//!
//! L3 semantics. It depends on `qc-sema` (L3), `qc-syntax` and `qc-project` (L2),
//! `qc-builtins` (L1) and `qc-diag` (L0).
//!
//! # Spec sections
//!
//! Implements ENGT-1, ENGT-3 and ENGT-4 of `docs/spec/engine-targets.md` (the generator in
//! `xtask` implements ENGT-2), and reports QCD-7.17 of `docs/spec/language-diagnostics.md`.
//! Written from the spec, not ported.

pub mod check;
mod tables;

pub use check::{BuiltinRef, declared_builtins, missing_builtins};
pub use tables::SOURCES;

use qc_builtins::table::BUILTINS;
use qc_project::{ModuleKind, Target};

/// How a progs names a builtin to the engine (ENGT-2.4).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum BuiltinKey {
    /// `= #N`, with `N` at least 1: the engine looks the builtin up by number.
    Number(u32),
    /// `= #0:NAME`: the engine looks the builtin up by this name.
    Name(&'static str),
}

/// One builtin in an engine's table.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Builtin {
    /// Its number or engine name.
    pub key: BuiltinKey,
    /// The QuakeC name its source declares it with; for a positional C table, which names
    /// none, the C function that implements it (ENGT-2.14).
    pub name: &'static str,
    /// Its function type, such as `float(string s)`; empty when its source gives none
    /// (ENGT-2.14, ENGT-2.15).
    pub signature: &'static str,
    /// The extensions it belongs to (ENGT-2.7); empty for id's builtins.
    pub extensions: &'static [&'static str],
}

/// One pinned fact source (ENGT-1.5).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Source {
    /// Its id in `sources.toml`.
    pub id: &'static str,
    /// The GitHub repository, `owner/name`.
    pub repo: &'static str,
    /// The pinned commit.
    pub commit: &'static str,
    /// The file's path in the repository.
    pub path: &'static str,
    /// The file's SHA-256.
    pub sha256: &'static str,
    /// The SPDX identifier of the repository's license file.
    pub license: &'static str,
    /// The license file's path in the repository.
    pub license_file: &'static str,
    /// The license file's SHA-256.
    pub license_sha256: &'static str,
}

/// An engine a project can target (ENGT-3.9).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Engine {
    /// id's engine.
    Vanilla,
    /// QuakeSpasm.
    QuakeSpasm,
    /// Ironwail.
    Ironwail,
    /// vkQuake.
    VkQuake,
    /// FTEQW.
    Fteqw,
    /// `DarkPlaces`.
    DarkPlaces,
    /// The 2021 KEX rerelease engine.
    Kex,
}

/// One part of an engine's table (ENGT-3.9, ENGT-3.11).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Layer {
    /// id's vanilla table, `qc-builtins` (BUILTIN-5).
    Vanilla,
    /// The rerelease `defs.qc`.
    Rerelease,
    /// FTEQW's `fteextensions.qc`, server QuakeC.
    Fteqw,
    /// FTEQW's `fteextensions.qc`, client QuakeC.
    FteqwCsqc,
    /// FTEQW's `fteextensions.qc`, menu QuakeC.
    FteqwMenuqc,
    /// DarkPlaces' `dpextensions.qc`.
    DarkPlaces,
    /// DarkPlaces' `csprogsdefs.qc`, client QuakeC.
    DarkPlacesCsqc,
    /// DarkPlaces' `menudefs.qc`, menu QuakeC.
    DarkPlacesMenuqc,
    /// QuakeSpasm's `pr_builtin` array.
    QuakeSpasm,
    /// QuakeSpasm's names for the rerelease's `#0:ex_` builtins.
    QuakeSpasmRerelease,
    /// Ironwail's `pr_builtindefs`, server QuakeC.
    Ironwail,
    /// Ironwail's `pr_builtindefs`, client QuakeC.
    IronwailCsqc,
    /// vkQuake's `pr_ssqcbuiltins` array.
    VkQuake,
    /// vkQuake's `pr_csqcbuiltins` array.
    VkQuakeCsqc,
    /// vkQuake's `extensionbuiltins`, server QuakeC.
    VkQuakeExt,
    /// vkQuake's `extensionbuiltins`, client QuakeC.
    VkQuakeExtCsqc,
}

/// id's builtin as a table entry.
impl From<&qc_builtins::Builtin> for Builtin {
    fn from(b: &qc_builtins::Builtin) -> Self {
        Self {
            key: BuiltinKey::Number(b.number),
            name: b.name,
            signature: b.prototype,
            extensions: &[],
        }
    }
}

impl Layer {
    /// The generated table of a layer; empty for [`Layer::Vanilla`], which is not generated.
    const fn generated(self) -> &'static [Builtin] {
        match self {
            Self::Vanilla => &[],
            Self::Rerelease => tables::RERELEASE_SSQC_BUILTINS,
            Self::Fteqw => tables::FTEQW_SSQC_BUILTINS,
            Self::FteqwCsqc => tables::FTEQW_CSQC_BUILTINS,
            Self::FteqwMenuqc => tables::FTEQW_MENUQC_BUILTINS,
            Self::DarkPlaces => tables::DARKPLACES_SSQC_BUILTINS,
            Self::DarkPlacesCsqc => tables::DARKPLACES_CLIENT_CSQC_BUILTINS,
            Self::DarkPlacesMenuqc => tables::DARKPLACES_MENU_MENUQC_BUILTINS,
            Self::QuakeSpasm => tables::QUAKESPASM_SSQC_BUILTINS,
            Self::QuakeSpasmRerelease => tables::QUAKESPASM_RERELEASE_SSQC_BUILTINS,
            Self::Ironwail => tables::IRONWAIL_SSQC_BUILTINS,
            Self::IronwailCsqc => tables::IRONWAIL_CSQC_BUILTINS,
            Self::VkQuake => tables::VKQUAKE_SSQC_BUILTINS,
            Self::VkQuakeCsqc => tables::VKQUAKE_CSQC_BUILTINS,
            Self::VkQuakeExt => tables::VKQUAKE_EXT_SSQC_BUILTINS,
            Self::VkQuakeExtCsqc => tables::VKQUAKE_EXT_CSQC_BUILTINS,
        }
    }

    /// The layer's builtins, in source order.
    fn builtins(self) -> Vec<Builtin> {
        match self {
            Self::Vanilla => BUILTINS.iter().map(Builtin::from).collect(),
            Self::Rerelease
            | Self::Fteqw
            | Self::FteqwCsqc
            | Self::FteqwMenuqc
            | Self::DarkPlaces
            | Self::DarkPlacesCsqc
            | Self::DarkPlacesMenuqc
            | Self::QuakeSpasm
            | Self::QuakeSpasmRerelease
            | Self::Ironwail
            | Self::IronwailCsqc
            | Self::VkQuake
            | Self::VkQuakeCsqc
            | Self::VkQuakeExt
            | Self::VkQuakeExtCsqc => self.generated().to_vec(),
        }
    }

    /// The layer's entry for `key`.
    fn find(self, key: BuiltinKey) -> Option<Builtin> {
        match (self, key) {
            (Self::Vanilla, BuiltinKey::Number(n)) => qc_builtins::lookup(n).map(Builtin::from),
            (Self::Vanilla, BuiltinKey::Name(_)) => None,
            (
                Self::Rerelease
                | Self::Fteqw
                | Self::FteqwCsqc
                | Self::FteqwMenuqc
                | Self::DarkPlaces
                | Self::DarkPlacesCsqc
                | Self::DarkPlacesMenuqc
                | Self::QuakeSpasm
                | Self::QuakeSpasmRerelease
                | Self::Ironwail
                | Self::IronwailCsqc
                | Self::VkQuake
                | Self::VkQuakeCsqc
                | Self::VkQuakeExt
                | Self::VkQuakeExtCsqc,
                _,
            ) => self.generated().iter().find(|b| b.key == key).copied(),
        }
    }

    /// The layer's entry for the engine name `name` (ENGT-4.17); id's table names none.
    fn find_named(self, name: &str) -> Option<Builtin> {
        self.generated()
            .iter()
            .find(|b| matches!(b.key, BuiltinKey::Name(n) if n == name))
            .copied()
    }
}

impl Engine {
    /// Every engine, in the order of ENGT-3.9.
    pub const ALL: [Self; 7] = [
        Self::Vanilla,
        Self::QuakeSpasm,
        Self::Ironwail,
        Self::VkQuake,
        Self::Fteqw,
        Self::DarkPlaces,
        Self::Kex,
    ];

    /// The display name, such as `Ironwail` (ENGT-3.4).
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Vanilla => "Vanilla",
            Self::QuakeSpasm => "QuakeSpasm",
            Self::Ironwail => "Ironwail",
            Self::VkQuake => "vkQuake",
            Self::Fteqw => "FTEQW",
            Self::DarkPlaces => "DarkPlaces",
            Self::Kex => "KEX",
        }
    }

    /// The id, such as `ironwail` (ENGT-3.4).
    #[must_use]
    pub const fn id(self) -> &'static str {
        match self {
            Self::Vanilla => "vanilla",
            Self::QuakeSpasm => "quakespasm",
            Self::Ironwail => "ironwail",
            Self::VkQuake => "vkquake",
            Self::Fteqw => "fteqw",
            Self::DarkPlaces => "darkplaces",
            Self::Kex => "kex",
        }
    }

    /// The engine with the id `id`, if any (ENGT-3.4).
    #[must_use]
    pub fn from_id(id: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|engine| engine.id() == id)
    }

    /// The engine a project file's target selects (ENGT-3.5, ENGT-3.6).
    #[must_use]
    pub const fn from_target(target: Target) -> Self {
        match target {
            Target::Quake => Self::Vanilla,
            Target::QuakeSpasm => Self::QuakeSpasm,
            Target::Ironwail => Self::Ironwail,
            Target::VkQuake => Self::VkQuake,
            Target::Rerelease => Self::Kex,
            Target::Fte => Self::Fteqw,
            Target::Dp => Self::DarkPlaces,
        }
    }

    /// The layers of this engine's table for `kind`, first first; none when the engine has no
    /// table for that kind (ENGT-3.9, ENGT-3.11).
    const fn layers(self, kind: ModuleKind) -> &'static [Layer] {
        match (self, kind) {
            (Self::Vanilla, ModuleKind::Ssqc) => &[Layer::Vanilla],
            (Self::QuakeSpasm, ModuleKind::Ssqc) => &[
                Layer::Vanilla,
                Layer::QuakeSpasm,
                Layer::QuakeSpasmRerelease,
            ],
            (Self::Ironwail, ModuleKind::Ssqc) => &[Layer::Vanilla, Layer::Ironwail],
            (Self::Ironwail, ModuleKind::Csqc) => &[Layer::IronwailCsqc],
            (Self::VkQuake, ModuleKind::Ssqc) => {
                &[Layer::VkQuakeExt, Layer::Vanilla, Layer::VkQuake]
            }
            (Self::VkQuake, ModuleKind::Csqc) => &[Layer::VkQuakeExtCsqc, Layer::VkQuakeCsqc],
            (Self::Fteqw, ModuleKind::Ssqc) => &[Layer::Fteqw],
            (Self::Fteqw, ModuleKind::Csqc) => &[Layer::FteqwCsqc],
            (Self::Fteqw, ModuleKind::Menuqc) => &[Layer::FteqwMenuqc],
            (Self::DarkPlaces, ModuleKind::Ssqc) => &[Layer::Vanilla, Layer::DarkPlaces],
            (Self::DarkPlaces, ModuleKind::Csqc) => &[Layer::DarkPlacesCsqc],
            (Self::DarkPlaces, ModuleKind::Menuqc) => &[Layer::DarkPlacesMenuqc],
            (Self::Kex, ModuleKind::Ssqc) => &[Layer::Rerelease],
            (
                Self::Vanilla | Self::QuakeSpasm | Self::Kex,
                ModuleKind::Csqc | ModuleKind::Menuqc,
            )
            | (Self::Ironwail | Self::VkQuake, ModuleKind::Menuqc) => &[],
        }
    }

    /// Whether the database has a builtin table of this engine for modules of `kind`: every
    /// engine has one for server QuakeC, Ironwail, vkQuake, FTEQW and DarkPlaces for client
    /// QuakeC, and only FTEQW and DarkPlaces for menu QuakeC (ENGT-3.11).
    #[must_use]
    pub const fn has_table(self, kind: ModuleKind) -> bool {
        !self.layers(kind).is_empty()
    }

    /// The engine's builtin table for modules of `kind`: each key once, the first layer that
    /// has it giving the entry, in layer and then source order (ENGT-3.9, ENGT-3.11). Empty
    /// when the engine has no table for that kind.
    #[must_use]
    pub fn builtins(self, kind: ModuleKind) -> Vec<Builtin> {
        let mut table: Vec<Builtin> = Vec::new();
        for layer in self.layers(kind) {
            for builtin in layer.builtins() {
                if !table.iter().any(|b| b.key == builtin.key) {
                    table.push(builtin);
                }
            }
        }
        table
    }

    /// The engine's entry for `key` in its table for modules of `kind`, if it has one
    /// (ENGT-3.9, ENGT-3.11).
    #[must_use]
    pub fn builtin(self, kind: ModuleKind, key: BuiltinKey) -> Option<Builtin> {
        self.layers(kind).iter().find_map(|layer| layer.find(key))
    }

    /// The engine's entry for the engine name `name` in its table for modules of `kind`, if it
    /// has one: [`Self::builtin`] of the [`BuiltinKey::Name`] `name` (ENGT-3.9, ENGT-4.17).
    #[must_use]
    pub fn builtin_named(self, kind: ModuleKind, name: &str) -> Option<Builtin> {
        self.layers(kind)
            .iter()
            .find_map(|layer| layer.find_named(name))
    }

    /// The extension names the engine declares for modules of `kind` (ENGT-3.10).
    #[must_use]
    pub const fn extensions(self, kind: ModuleKind) -> &'static [&'static str] {
        match (self, kind) {
            (Self::Fteqw, ModuleKind::Ssqc) => tables::FTEQW_SSQC_EXTENSIONS,
            (Self::Fteqw, ModuleKind::Csqc) => tables::FTEQW_CSQC_EXTENSIONS,
            (Self::Fteqw, ModuleKind::Menuqc) => tables::FTEQW_MENUQC_EXTENSIONS,
            (Self::DarkPlaces, ModuleKind::Ssqc) => tables::DARKPLACES_SSQC_EXTENSIONS,
            (Self::DarkPlaces, ModuleKind::Csqc) => tables::DARKPLACES_CLIENT_CSQC_EXTENSIONS,
            (Self::DarkPlaces, ModuleKind::Menuqc) => tables::DARKPLACES_MENU_MENUQC_EXTENSIONS,
            (Self::Kex, ModuleKind::Ssqc) => tables::RERELEASE_SSQC_EXTENSIONS,
            (Self::VkQuake, ModuleKind::Ssqc) => tables::VKQUAKE_EXT_SSQC_EXTENSIONS,
            (Self::VkQuake, ModuleKind::Csqc) => tables::VKQUAKE_EXT_CSQC_EXTENSIONS,
            (Self::Vanilla | Self::QuakeSpasm | Self::Ironwail, _)
            | (Self::VkQuake | Self::Kex, ModuleKind::Menuqc)
            | (Self::Kex, ModuleKind::Csqc) => &[],
        }
    }
}

