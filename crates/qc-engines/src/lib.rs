//! The engine-target database: which builtins and extensions each Quake engine supports.
//!
//! A QuakeC builtin is a function the engine implements, declared in QuakeC as `= #N`; the
//! number is the only link between the progs and the engine, and which numbers an engine has
//! differs from engine to engine. This crate holds a builtin table and an extension list for
//! seven engines ([`Engine`]), so the editor, the compiler and the agent know what a target
//! supports (LANG-6, AGT-9), and [`check`] reports a call of a builtin the target lacks
//! (PRIN-8).
//!
//! The tables of FTEQW, DarkPlaces and the 2021 rerelease are generated by
//! `cargo xtask engines` from three fact sources pinned by commit and SHA-256 in
//! `sources.toml` ([`SOURCES`]); only facts are extracted, and ADR-0014 records the legal
//! basis. The vanilla table is `qc-builtins`', ported from id's engine.
//!
//! # Layer
//!
//! L3 semantics. It depends on `qc-sema` (L3), `qc-syntax` and `qc-project` (L2),
//! `qc-builtins` (L1) and `qc-diag` (L0).
//!
//! # Spec sections
//!
//! Implements ENGT-1, ENGT-3 and ENGT-4 of `docs/spec/engine-targets.md` (the generator in
//! `xtask` implements ENGT-2), and reports QCD-7.17 of `docs/spec/language-diagnostics.md`.
//! Written from the spec, not ported.

pub mod check;
mod tables;

pub use check::{FileDiagnostic, missing_builtins};
pub use tables::SOURCES;

use qc_builtins::table::BUILTINS;
use qc_project::Target;

/// How a progs names a builtin to the engine (ENGT-2.4).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum BuiltinKey {
    /// `= #N`, with `N` at least 1: the engine looks the builtin up by number.
    Number(u32),
    /// `= #0:NAME`: the engine looks the builtin up by this name.
    Name(&'static str),
}

/// One builtin in an engine's table.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Builtin {
    /// Its number or engine name.
    pub key: BuiltinKey,
    /// The QuakeC name its source declares it with.
    pub name: &'static str,
    /// Its function type, such as `float(string s)`.
    pub signature: &'static str,
    /// The extensions it belongs to (ENGT-2.7); empty for id's builtins.
    pub extensions: &'static [&'static str],
}

/// One pinned fact source (ENGT-1.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Source {
    /// Its id in `sources.toml`.
    pub id: &'static str,
    /// The GitHub repository, `owner/name`.
    pub repo: &'static str,
    /// The pinned commit.
    pub commit: &'static str,
    /// The file's path in the repository.
    pub path: &'static str,
    /// The file's SHA-256.
    pub sha256: &'static str,
    /// The SPDX identifier of the repository's license file.
    pub license: &'static str,
    /// The license file's path in the repository.
    pub license_file: &'static str,
    /// The license file's SHA-256.
    pub license_sha256: &'static str,
}

/// An engine a project can target (ENGT-3.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Engine {
    /// id's engine.
    Vanilla,
    /// QuakeSpasm.
    QuakeSpasm,
    /// Ironwail.
    Ironwail,
    /// vkQuake.
    VkQuake,
    /// FTEQW.
    Fteqw,
    /// `DarkPlaces`.
    DarkPlaces,
    /// The 2021 KEX rerelease engine.
    Kex,
}

/// One part of an engine's table (ENGT-3.1).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Layer {
    /// id's vanilla table, `qc-builtins` (BUILTIN-5).
    Vanilla,
    /// The rerelease `defs.qc`.
    Rerelease,
    /// FTEQW's `fteextensions.qc`, server QuakeC.
    Fteqw,
    /// DarkPlaces' `dpextensions.qc`.
    DarkPlaces,
}

/// id's builtin as a table entry.
const fn vanilla(b: &qc_builtins::Builtin) -> Builtin {
    Builtin {
        key: BuiltinKey::Number(b.number),
        name: b.name,
        signature: b.prototype,
        extensions: &[],
    }
}

impl Layer {
    /// The generated table of a layer; empty for [`Layer::Vanilla`], which is not generated.
    const fn generated(self) -> &'static [Builtin] {
        match self {
            Self::Vanilla => &[],
            Self::Rerelease => tables::RERELEASE_BUILTINS,
            Self::Fteqw => tables::FTEQW_BUILTINS,
            Self::DarkPlaces => tables::DARKPLACES_BUILTINS,
        }
    }

    /// The layer's builtins, in source order.
    fn builtins(self) -> Vec<Builtin> {
        match self {
            Self::Vanilla => BUILTINS.iter().map(vanilla).collect(),
            Self::Rerelease | Self::Fteqw | Self::DarkPlaces => self.generated().to_vec(),
        }
    }

    /// The layer's entry for `key`.
    fn find(self, key: BuiltinKey) -> Option<Builtin> {
        match (self, key) {
            (Self::Vanilla, BuiltinKey::Number(n)) => qc_builtins::lookup(n).map(vanilla),
            (Self::Vanilla, BuiltinKey::Name(_)) => None,
            (Self::Rerelease | Self::Fteqw | Self::DarkPlaces, _) => {
                self.generated().iter().find(|b| b.key == key).copied()
            }
        }
    }
}

impl Engine {
    /// Every engine, in the order of ENGT-3.1.
    pub const ALL: [Self; 7] = [
        Self::Vanilla,
        Self::QuakeSpasm,
        Self::Ironwail,
        Self::VkQuake,
        Self::Fteqw,
        Self::DarkPlaces,
        Self::Kex,
    ];

    /// The display name, such as `Ironwail` (ENGT-3.4).
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Vanilla => "Vanilla",
            Self::QuakeSpasm => "QuakeSpasm",
            Self::Ironwail => "Ironwail",
            Self::VkQuake => "vkQuake",
            Self::Fteqw => "FTEQW",
            Self::DarkPlaces => "DarkPlaces",
            Self::Kex => "KEX",
        }
    }

    /// The id, such as `ironwail` (ENGT-3.4).
    #[must_use]
    pub const fn id(self) -> &'static str {
        match self {
            Self::Vanilla => "vanilla",
            Self::QuakeSpasm => "quakespasm",
            Self::Ironwail => "ironwail",
            Self::VkQuake => "vkquake",
            Self::Fteqw => "fteqw",
            Self::DarkPlaces => "darkplaces",
            Self::Kex => "kex",
        }
    }

    /// The engine with the id `id`, if any (ENGT-3.4).
    #[must_use]
    pub fn from_id(id: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|engine| engine.id() == id)
    }

    /// The engine a project file's target selects (ENGT-3.5, ENGT-3.6).
    #[must_use]
    pub const fn from_target(target: Target) -> Self {
        match target {
            Target::Quake => Self::Vanilla,
            Target::QuakeSpasm => Self::QuakeSpasm,
            Target::Ironwail => Self::Ironwail,
            Target::VkQuake => Self::VkQuake,
            Target::Rerelease => Self::Kex,
            Target::Fte => Self::Fteqw,
            Target::Dp => Self::DarkPlaces,
        }
    }

    /// The layers of this engine's table, first first (ENGT-3.1).
    const fn layers(self) -> &'static [Layer] {
        match self {
            Self::Vanilla | Self::QuakeSpasm => &[Layer::Vanilla],
            Self::Ironwail | Self::VkQuake => &[Layer::Vanilla, Layer::Rerelease],
            Self::Fteqw => &[Layer::Fteqw],
            Self::DarkPlaces => &[Layer::Vanilla, Layer::DarkPlaces],
            Self::Kex => &[Layer::Rerelease],
        }
    }

    /// The engine's builtin table: each key once, the first layer that has it giving the
    /// entry, in layer and then source order (ENGT-3.1).
    #[must_use]
    pub fn builtins(self) -> Vec<Builtin> {
        let mut table: Vec<Builtin> = Vec::new();
        for layer in self.layers() {
            for builtin in layer.builtins() {
                if !table.iter().any(|b| b.key == builtin.key) {
                    table.push(builtin);
                }
            }
        }
        table
    }

    /// The engine's entry for `key`, if its table has one (ENGT-3.1).
    #[must_use]
    pub fn builtin(self, key: BuiltinKey) -> Option<Builtin> {
        self.layers().iter().find_map(|layer| layer.find(key))
    }

    /// The extension names the engine declares (ENGT-3.3).
    #[must_use]
    pub const fn extensions(self) -> &'static [&'static str] {
        match self {
            Self::Fteqw => tables::FTEQW_EXTENSIONS,
            Self::DarkPlaces => tables::DARKPLACES_EXTENSIONS,
            Self::Kex => tables::RERELEASE_EXTENSIONS,
            Self::Vanilla | Self::QuakeSpasm | Self::Ironwail | Self::VkQuake => &[],
        }
    }
}

