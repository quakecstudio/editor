/// Every diagnostic message of the FTEQCC file `source`, in order.
fn messages(source: &str) -> Vec<String> {
    let mut db = Db::new();
    db.set_dialect(Dialect::Fteqcc);
    db.set_file(
        FileId(0),
        PathBuf::from("t.qc"),
        format!("{source}\n").into_bytes(),
    );
    let analysis = db.analyze_module(&ModuleInput {
        compiled: vec![FileId(0)],
        command_line: CommandLine::new::<&str>(&[]),
        ..ModuleInput::default()
    });
    analysis
        .diagnostics()
        .map(|d| d.diagnostic.message.clone())
        .collect()
}

/// Each case's program: its prelude, by its index in [`PRELUDES`], and its last line.
fn check(cases: &[(usize, &str, &[&str])]) {
    for &(prelude, last, expected) in cases {
        let source = format!("{}\n{last}", PRELUDES[prelude]);
        assert_eq!(messages(&source), expected, "{source}");
    }
}

