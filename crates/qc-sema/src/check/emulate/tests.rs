// spec FTEF-27.2: each opcode the target lacks is emulated as `QCC_PR_StatementFlags` emulates
// it, and every other is refused
// spec FTEF-27.9: the opcodes it replaces by others are replaced so
#[test]
fn every_opcode_is_emulated_as_the_switch_says() {
    for &(op, expected) in EMULATED {
        assert_eq!(format!("{:?}", emulation(op)), expected, "{op:?}");
    }
    let listed = |op: Op| EMULATED.iter().any(|&(listed, _)| listed == op);
    for op in Op::ALL.into_iter().filter(|&op| !listed(op)) {
        assert_eq!(emulation(op), Emulation::Refuse, "{op:?}");
    }
}

// spec FTEF-27.8: a numeric conversion emits `QCC_TryEvaluateCast`'s opcodes in order, and any
// other none
#[test]
fn every_conversion_emits_its_opcodes() {
    for &(from, to, expected) in CONVERTED {
        assert_eq!(
            format!("{:?}", conversion_opcodes(from, to)),
            expected,
            "{from:?} to {to:?}"
        );
    }
    assert!(conversion_opcodes(Etype::Float, Etype::Float).is_empty());
    assert!(conversion_opcodes(Etype::String, Etype::Float).is_empty());
}
