#!/usr/bin/env python3
"""Create or update milestones, labels and issues on GitHub from the plan.

Idempotent: each issue body carries <!-- plan-key: KEY -->; existing issues are
found by that marker and updated instead of duplicated. Dependencies are written
as issue links once every issue exists.

Usage:
  python3 plan/apply.py --repo quakecstudio/editor --dry-run
  python3 plan/apply.py --repo quakecstudio/editor
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from urllib.parse import quote

from check import PHASE_ORDER, check, load_backlog, load_requirements

MARKER = re.compile(r"<!-- plan-key: ([A-Z0-9-]+) -->")


TRANSIENT = ("connection reset", "eof", "timeout", "tls handshake", "http 502", "http 503", "http 504")


class TransientWrite(RuntimeError):
    """A create may or may not have happened; the caller must check before retrying."""


def gh(args: list[str], payload: dict | None = None) -> object:
    """Call the GitHub API. Writes are paced; rate limits are retried.

    Network failures are retried for reads and PATCHes (idempotent). A failed POST raises
    TransientWrite instead, because GitHub may have created the object anyway.
    """
    cmd = ["gh", "api", *args]
    is_post = "POST" in args
    if payload is not None:
        cmd += ["--input", "-"]
    writing = payload is not None
    for attempt in range(6):
        out = subprocess.run(cmd, input=json.dumps(payload) if writing else None,
                             capture_output=True, text=True)
        if out.returncode == 0:
            if writing:
                time.sleep(1.0)  # stay under GitHub's content-creation limits
            if not out.stdout.strip():
                return None
            return json.loads(out.stdout)
        if "rate limit" in out.stderr.lower() or "HTTP 429" in out.stderr:
            wait = 30 * (attempt + 1)
            print(f"rate limited; waiting {wait}s", file=sys.stderr)
            time.sleep(wait)
            continue
        if any(t in out.stderr.lower() for t in TRANSIENT):
            if is_post:
                raise TransientWrite(out.stderr.strip())
            time.sleep(5 * (attempt + 1))
            continue
        raise RuntimeError(f"gh api {' '.join(args)} failed: {out.stderr.strip()}")
    raise RuntimeError(f"gh api {' '.join(args)} still rate limited after retries")


FOOTER = re.compile(r"\n*---\n_Generated by \[Claude Code\]\([^)]*\)_\s*$")


def normalize(body: str) -> str:
    """GitHub returns CRLF line endings, and this session's GitHub proxy appends a footer."""
    return FOOTER.sub("", body.replace("\r\n", "\n"))


def gh_list(path: str) -> list:
    """Page through a list endpoint by page number.

    gh's own pagination follows Link headers that use repositories/{id}/ paths, which the
    session proxy rejects, so pages are requested explicitly on the repos/ path.
    """
    items: list = []
    sep = "&" if "?" in path else "?"
    page = 1
    while True:
        batch = gh([f"{path}{sep}per_page=100&page={page}"])
        items.extend(batch)
        if len(batch) < 100:
            return items
        page += 1


def render_body(issue: dict, reqs: dict, meta: dict, numbers: dict[str, int], titles: dict[str, str]) -> str:
    ms = {m["key"]: m for m in meta["milestones"]}[issue["milestone"]]
    lines = [
        f"**Plan key:** `{issue['key']}` · **Phase:** {ms['title']} · **Size:** {issue['size']} ({meta['sizes'][issue['size']]})",
        "",
        "**Requirements**",
        *[f"- `{r}` {reqs[r]['text']}" for r in issue["reqs"]],
        "",
        "## Deliverable",
        *[f"- {d}" for d in issue["deliverable"]],
        "",
        "## Acceptance criteria",
        *[f"- [ ] {a}" for a in issue["acceptance"]],
        "",
        "## Verification",
        *[f"- {v}" for v in issue["verify"]],
    ]
    if issue.get("depends"):
        lines += ["", "## Depends on"]
        for d in issue["depends"]:
            ref = f"#{numbers[d]}" if d in numbers else f"`{d}`"
            lines.append(f"- [ ] {ref} {titles[d]}")
    if "clean-room:impl" in issue["labels"]:
        lines += ["", "> Clean-room implementation: work only from `docs/spec/`. Do not read the matching GPL source."]
    if "clean-room:spec" in issue["labels"]:
        lines += ["", "> Clean-room spec: record every GPL file you read in `docs/clean-room/readers.md`. You may not implement the matching code."]
    lines += ["", "## Definition of done", *[f"- [ ] {d}" for d in meta["definition_of_done"]], "",
              f"<!-- plan-key: {issue['key']} -->"]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    reqs = load_requirements()
    meta, issues = load_backlog()
    errors = check(reqs, meta, issues)
    if errors:
        print("plan/check.py fails; fix the plan first", file=sys.stderr)
        return 1
    issues.sort(key=lambda i: (PHASE_ORDER.index(i["milestone"]), i["key"]))
    for i in issues:  # Size is shown on the Project board through a size:* label
        i["labels"] = [*i["labels"], f"size:{i['size']}"]
    titles = {i["key"]: i["title"] for i in issues}
    repo = f"repos/{args.repo}"

    all_labels = [l for group in meta["labels"].values() for l in group]
    if args.dry_run:
        print(f"would ensure {len(all_labels)} labels, {len(meta['milestones'])} milestones, {len(issues)} issues")
        for i in issues[:3]:
            print("-" * 60, f"\n{i['title']}\n", render_body(i, reqs, meta, {}, titles))
        return 0

    existing_labels = {l["name"]: l for l in gh_list(f"{repo}/labels")}
    for l in all_labels:
        body = {"name": l["name"], "color": l["color"], "description": l["description"]}
        have = existing_labels.get(l["name"])
        if have and have["color"] == l["color"] and (have["description"] or "") == l["description"]:
            continue
        if have:
            gh(["-X", "PATCH", f"{repo}/labels/{quote(l['name'], safe='')}"], body)
        else:
            gh(["-X", "POST", f"{repo}/labels"], body)

    ms_existing = {m["title"]: m for m in gh_list(f"{repo}/milestones?state=all")}
    ms_numbers = {t: m["number"] for t, m in ms_existing.items()}
    ms_by_key = {}
    for m in meta["milestones"]:
        body = {"title": m["title"], "description": f"Gate: {m['gate']}"}
        if m["title"] in ms_numbers and ms_existing[m["title"]]["description"] == body["description"]:
            ms_by_key[m["key"]] = ms_numbers[m["title"]]
            continue
        if m["title"] in ms_numbers:
            gh(["-X", "PATCH", f"{repo}/milestones/{ms_numbers[m['title']]}"], body)
            ms_by_key[m["key"]] = ms_numbers[m["title"]]
        else:
            ms_by_key[m["key"]] = gh(["-X", "POST", f"{repo}/milestones"], body)["number"]

    current: dict[str, dict] = {}

    def scan() -> dict[str, int]:
        found: dict[str, int] = {}
        for gi in gh_list(f"{repo}/issues?state=all"):
            m = MARKER.search(gi.get("body") or "")
            if m:
                found[m.group(1)] = gi["number"]
                current[m.group(1)] = gi
        return found

    numbers = scan()

    # pass 1: create missing issues; pass 2: write bodies with dependency links
    for i in issues:
        if i["key"] not in numbers:
            body = render_body(i, reqs, meta, numbers, titles)
            for _ in range(5):
                try:
                    created = gh(["-X", "POST", f"{repo}/issues"],
                                 {"title": i["title"], "body": body, "labels": i["labels"], "milestone": ms_by_key[i["milestone"]]})
                    numbers[i["key"]] = created["number"]
                    break
                except TransientWrite as e:
                    print(f"{i['key']}: create interrupted ({e}); checking before retry", file=sys.stderr)
                    time.sleep(10)
                    numbers.update(scan())
                    if i["key"] in numbers:
                        break
            else:
                raise RuntimeError(f"{i['key']}: could not create after retries")
            print(f"created #{numbers[i['key']]} {i['key']} {i['title']}")
    changed = 0
    for i in issues:
        body = render_body(i, reqs, meta, numbers, titles)
        have = current.get(i["key"], {})
        same = (normalize(have.get("body") or "") == body and have.get("title") == i["title"]
                and sorted(l["name"] for l in have.get("labels", [])) == sorted(i["labels"])
                and (have.get("milestone") or {}).get("number") == ms_by_key[i["milestone"]])
        if same:
            continue
        gh(["-X", "PATCH", f"{repo}/issues/{numbers[i['key']]}"],
           {"title": i["title"], "body": body, "labels": i["labels"], "milestone": ms_by_key[i["milestone"]]})
        changed += 1
    print(f"done: {len(issues)} issues in sync ({changed} updated)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
